// Copies assets/3d/*.webp to public/3d/<name>.<hash>.webp and writes the URL map
// the site imports. Filenames change when the pixels change, so public/_headers
// can cache /3d/* for a year as immutable.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "assets/3d");
const outDir = path.join(root, "public/3d");
const manifestPath = path.join(root, "src/generated/art.ts");

export function hashArt() {
  mkdirSync(outDir, { recursive: true });
  for (const file of readdirSync(outDir)) {
    if (file.endsWith(".webp")) rmSync(path.join(outDir, file));
  }
  const map: Record<string, string> = {};
  for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".webp")).sort()) {
    const buf = readFileSync(path.join(srcDir, file));
    const hash = createHash("sha256").update(buf).digest("hex").slice(0, 10);
    const name = file.replace(/\.webp$/, "");
    const hashed = `${name}.${hash}.webp`;
    writeFileSync(path.join(outDir, hashed), buf);
    map[name] = `/3d/${hashed}`;
  }
  mkdirSync(path.dirname(manifestPath), { recursive: true });
  writeFileSync(
    manifestPath,
    "// Generated by scripts/hash-3d.ts. Do not edit.\n" +
      `export const ART_SRC = ${JSON.stringify(map, null, 2)} as const;\n`,
  );
  console.log(`Hashed ${Object.keys(map).length} 3D renders`);
}

hashArt();
